import { DB_SCHEMA } from "./db.js";
import { DROP_SCHEMA_SQL, SCHEMA_SQL } from "./schema.js";

export const SUPABASE_MIGRATION_FILE = "supabase/migrations/20261107202600_infinitum_revenue.sql";
export const DROP_MIGRATION_FILE = "supabase/migrations/20261108200000_genesis_drop.sql";

/**
 * Every Supabase migration for this product, in apply order. Each is generated
 * from src/schema.ts; a test fails if a committed file drifts. Never change the
 * SQL behind a migration that has been applied: add a new entry instead.
 */
export function supabaseMigrations(): { file: string; sql: string }[] {
  return [
    { file: SUPABASE_MIGRATION_FILE, sql: supabaseMigrationSql() },
    { file: DROP_MIGRATION_FILE, sql: wrap(DROP_SCHEMA_SQL, "Genesis Drop early-viewer registrations (Solana).") },
  ];
}

/**
 * The base migration: SCHEMA_SQL inside its own schema in the shared Infinitum
 * Corp project, with row-level security on every table and no policies, so the
 * anon / authenticated keys (Data API) can't read or write anything. Only the
 * Worker, connecting over DATABASE_URL, can.
 *
 * Regenerate with `npm run db:gen` after editing src/schema.ts.
 */
export function supabaseMigrationSql(): string {
  return wrap(SCHEMA_SQL, "Infinitum revenue API: one schema per product in the Infinitum Corp project.");
}

function wrap(body: string, title: string): string {
  return `-- GENERATED by \`npm run db:gen\` from src/schema.ts. Do not edit by hand.
-- ${title}

create schema if not exists ${DB_SCHEMA};
set search_path to ${DB_SCHEMA}, public;
${body.trimEnd()}

-- Row-level security on every table, with no policies: the Data API keys get
-- nothing. The Worker connects as a privileged role over DATABASE_URL.
do $$
declare t record;
begin
  for t in select tablename from pg_tables where schemaname = '${DB_SCHEMA}' loop
    execute format('alter table %I.%I enable row level security', '${DB_SCHEMA}', t.tablename);
  end loop;
end
$$;

revoke all on schema ${DB_SCHEMA} from anon, authenticated;
revoke all on all tables in schema ${DB_SCHEMA} from anon, authenticated;
revoke all on all sequences in schema ${DB_SCHEMA} from anon, authenticated;
alter default privileges in schema ${DB_SCHEMA} revoke all on tables from anon, authenticated;

reset search_path;
`;
}
